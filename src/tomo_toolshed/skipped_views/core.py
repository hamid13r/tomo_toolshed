"""Core processing logic for the skipped-views tool.

Reads WarpTools tilt-series XML files and either:

  * **flip mode** (default) -- rewrites each ``UseTilt`` value to True/False from
    the etomo ``taSolution.log`` (with optional dose / tilt-angle selection), or
  * **delete mode** (``--delete``) -- physically removes the excluded tilts from
    both the XML and the matching ``.tomostar`` file, renumbering grid Z-slices
    and indexed per-tilt elements so the file stays internally consistent.

Warp 2 tilt-series XML is UTF-8 *with a BOM*; we serialize it back byte-for-byte
(verified by a round-trip test) so an unedited file is unchanged on disk. Kept
import-clean of click's *command* layer (only ``click.echo`` is used for
messaging) so the behavior can be reused and tested independently of the CLI.
"""

import os
import shutil
import glob
import io
import ntpath
import re
import tempfile
from collections import defaultdict
from datetime import datetime

import pandas as pd
import click
from lxml import etree

# Warp 2 tilt-series XML files are UTF-8 *with a BOM* and start with this exact
# declaration. lxml drops the BOM and single-quotes the declaration, so we emit
# both ourselves and only let lxml serialize the body (see serialize_xml).
XML_BOM = b"\xef\xbb\xbf"
XML_DECL = b'<?xml version="1.0" encoding="utf-8"?>\n'


# --------------------------------------------------------------------------- #
# XML I/O helpers
# --------------------------------------------------------------------------- #
UTF16_LE_BOM = b"\xff\xfe"
UTF16_BE_BOM = b"\xfe\xff"


def _decode_xml_bytes(raw):
    """Decode raw XML bytes -> (text, encoding_name). Handles Warp 2 (UTF-8
    with BOM) and Warp 1 (.NET, UTF-16 LE with BOM) files."""
    if raw.startswith(UTF16_LE_BOM):
        return raw[2:].decode("utf-16-le"), "utf-16"
    if raw.startswith(UTF16_BE_BOM):
        # Read fine; written back as UTF-16 LE (what .NET / Warp 1 writes).
        return raw[2:].decode("utf-16-be"), "utf-16"
    if raw.startswith(XML_BOM):
        return raw[3:].decode("utf-8"), "utf-8"
    return raw.decode("utf-8"), "utf-8"


def parse_xml(path):
    """Parse a Warp XML preserving all whitespace exactly.

    Warp 1 writes UTF-16 with CRLF between elements (but LF inside per-tilt
    lists). An XML parser normalizes CR away, so before parsing we turn every
    CR into a ``&#13;`` character reference; lxml then keeps it verbatim in
    .text/.tail and serialize_xml turns it back into a raw CR.
    """
    with open(path, "rb") as fh:
        raw = fh.read()
    text, enc = _decode_xml_bytes(raw)
    decl_end = text.find("?>") + 2 if text.startswith("<?xml") else 0
    root_start = text.index("<", decl_end)
    # Prolog whitespace is regenerated by serialize_xml; char refs are only
    # legal inside the root element, so only escape CRs from there on.
    decl = text[:decl_end] + text[decl_end:root_start].replace("\r", "")
    body = text[root_start:]
    end = body.rfind(">") + 1
    body = body[:end].replace("\r", "&#13;") + body[end:].replace("\r", "")
    if enc == "utf-8":
        data = XML_BOM + (decl + body).encode("utf-8")
    else:
        # Re-encode with the original BOM so lxml's docinfo.encoding records
        # the original encoding (used by serialize_xml).
        data = UTF16_LE_BOM + (decl + body).encode("utf-16-le")
    parser = etree.XMLParser(remove_blank_text=False, strip_cdata=False)
    return etree.parse(io.BytesIO(data), parser)


def serialize_xml(tree):
    """Serialize a tree back to Warp's exact on-disk byte format.

    lxml preserves element .text/.tail verbatim (so tabs, newlines and the
    "first value on the open tag line" layout survive), but it (a) drops the
    BOM, (b) writes the declaration with single quotes, (c) writes self-closing
    tags as ``"/>`` where Warp writes ``" />`` and (d) escapes CR as ``&#13;``.
    We fix all four so an unedited parse round-trips byte-for-byte (verified by
    the round-trip tests for Warp 2 UTF-8 and Warp 1 UTF-16/CRLF files).
    """
    body = etree.tostring(tree, xml_declaration=False, encoding="utf-8")
    body = body.replace(b'"/>', b'" />')
    enc = (tree.docinfo.encoding or "utf-8").lower()
    if enc.startswith("utf-16"):
        text = body.decode("utf-8").replace("&#13;", "\r")
        nl = "\r\n" if "\r" in text else "\n"
        text = '<?xml version="1.0" encoding="utf-16"?>' + nl + text
        return UTF16_LE_BOM + text.encode("utf-16-le")
    body = body.replace(b"&#13;", b"\r")
    nl = b"\r\n" if b"\r" in body else b"\n"
    return XML_BOM + XML_DECL.rstrip(b"\n") + nl + body


def atomic_write_bytes(path, data):
    """Write bytes to a temp file in the same dir, then atomically replace."""
    directory = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(dir=directory, suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise


def make_backup(src, backup_base):
    """Copy ``src`` to ``backup_base``; if that exists, try ``backup_base.1``,
    ``.2`` ... and use the first free name. Returns the backup path used."""
    candidate = backup_base
    i = 1
    while os.path.exists(candidate):
        candidate = f"{backup_base}.{i}"
        i += 1
    shutil.copy2(src, candidate)
    return candidate


# --------------------------------------------------------------------------- #
# Schema helpers -- everything is derived from the file, nothing hardcoded.
# --------------------------------------------------------------------------- #
def split_lines(text):
    """Split a per-tilt text block into its entries.

    Warp writes these with no leading/trailing newline, but we defensively drop
    a single trailing empty entry in case a file has one.
    """
    parts = (text or "").split("\n")
    if parts and parts[-1] == "":
        parts = parts[:-1]
    return parts


def get_n_tilts(root):
    """Number of tilts N == number of UseTilt entries."""
    ut = root.find("UseTilt")
    if ut is None or ut.text is None:
        return None
    return len(split_lines(ut.text))


def per_tilt_text_elems(root, n):
    """Top-level elements whose text is a newline list of length N.

    Enumerated by counting lines, not by a hardcoded name list. Elements with
    child nodes (grids) or an ID attribute (per-tilt indexed elements, handled
    separately) are excluded.
    """
    out = []
    for el in root:
        if len(el) > 0 or "ID" in el.attrib or el.text is None:
            continue
        if len(split_lines(el.text)) == n and n > 0:
            out.append(el)
    return out


def per_tilt_indexed(root, n):
    """Groups of sibling elements carrying an ID attribute of 0..N-1
    (e.g. <TiltPS1D ID="k">, <TiltSimulatedScale ID="k">)."""
    groups = defaultdict(list)
    for el in root:
        if "ID" in el.attrib:
            groups[el.tag].append(el)
    result = {}
    for tag, els in groups.items():
        if len(els) == n:
            ids = sorted(int(e.get("ID")) for e in els)
            if ids == list(range(n)):
                result[tag] = els
    return result


def per_tilt_grids(root, n):
    """Grid elements (Width/Height/Depth + <Node>) whose Depth == N, i.e. Z
    indexes tilts. Grids with Depth != N are global and left untouched."""
    out = []
    for el in root:
        depth = el.get("Depth")
        if depth is not None and el.find("Node") is not None and int(depth) == n:
            out.append(el)
    return out


def parse_dose(root):
    """Per-tilt accumulated dose as floats.

    NOTE: the original ElementTree code did ``root.findall('Dose')`` and then
    ``float(elem.text.strip())`` -- but <Dose> is a single newline-separated
    block, so that raised ValueError and the --max-tilt mode never worked. Here
    we split the block correctly.
    """
    dose_el = root.find("Dose")
    return [float(x) for x in split_lines(dose_el.text)]


def _tilt_lookup(root, tilts_in_log, n):
    """Return f(i) -> tilt angle of XML tilt index i.

    ``tilts_in_log`` is either a dict {view(1-based): tilt} (what read_log
    returns) or a list already aligned to the XML tilt index. With a dict, a
    view missing from the log falls back to the XML <Angles> value. (Indexing
    the log's tilt *list* by XML index was wrong whenever the log does not
    start at view 1.)
    """
    if isinstance(tilts_in_log, dict):
        angles = [float(a) for a in split_lines(root.find("Angles").text)]
        return lambda i: tilts_in_log.get(i + 1, angles[i])
    return lambda i: tilts_in_log[i]


# --------------------------------------------------------------------------- #
# Selection: one keep-mask consumed by both the flip and delete paths.
# --------------------------------------------------------------------------- #
def compute_keep_mask(root, views_in_log, tilts_in_log, all_true=False,
                      n_tilts=0, max_tilt=0):
    """Return a list[bool] of length N; True == keep this tilt.

    View numbers in taSolution.log are 1-based (tilt index i -> view i+1).

    Precedence: ``all_true`` > ``n_tilts`` > ``max_tilt`` > plain in-log keep.
      * ``n_tilts`` keeps the N lowest-dose tilts among those still in the log.
      * ``max_tilt`` keeps in-log tilts within ``max_tilt`` degrees of the
        lowest-dose tilt.
    """
    n = get_n_tilts(root)
    if all_true:
        return [True] * n

    in_log = [(i + 1) in views_in_log for i in range(n)]

    if n_tilts and n_tilts > 0:
        dose = parse_dose(root)
        candidates = sorted((i for i in range(n) if in_log[i]),
                            key=lambda i: dose[i])
        keep = set(candidates[:n_tilts])
        return [i in keep for i in range(n)]

    if max_tilt and max_tilt > 0:
        dose = parse_dose(root)
        min_dose_idx = dose.index(min(dose))
        tilt_of = _tilt_lookup(root, tilts_in_log, n)
        threshold = abs(tilt_of(min_dose_idx)) + max_tilt
        return [in_log[i] and (abs(tilt_of(i)) <= threshold)
                for i in range(n)]

    return in_log


# --------------------------------------------------------------------------- #
# Log reading
# --------------------------------------------------------------------------- #
def read_log(log_path):
    """Return (views_in_log:set, tilts_in_log:dict view->tilt) from a
    taSolution.log, or None if the file is missing / has no data table.

    When local alignments are enabled in etomo, taSolution.log holds the global
    solution table followed by one table per local area (each with its own
    ``view rotation tilt ...`` header). Only the first (global) table is used;
    concatenating them used to turn the ``view`` column into strings, so no
    view matched and every tilt was excluded.
    """
    if not os.path.exists(log_path):
        return None
    with open(log_path, "r") as f:
        lines = f.read().splitlines()
    header_idx = next(
        (idx for idx, line in enumerate(lines)
         if line.split()[:1] == ["view"]), None
    )
    if header_idx is None:
        return None
    table = [lines[header_idx]]
    for line in lines[header_idx + 1:]:
        parts = line.split()
        if not parts or not parts[0].lstrip("-").isdigit():
            break  # blank line / next header ends the global table
        table.append(line)
    if len(table) == 1:
        return None
    df = pd.read_csv(io.StringIO("\n".join(table)), sep=r"\s+")
    views = [int(v) for v in df["view"]]
    tilts = [float(t) for t in df["tilt"]]
    return set(views), dict(zip(views, tilts))


# --------------------------------------------------------------------------- #
# mdoc doses (--mdoc-dir)
# --------------------------------------------------------------------------- #
DOSE_TOL = 0.01  # e/A^2; smaller differences are formatting noise, not a warning


def _stem(name):
    """Movie name without directories (Windows or POSIX) and extension."""
    base = ntpath.basename(name.strip().replace("/", "\\"))
    return os.path.splitext(base)[0]


def find_mdoc(mdoc_dir, xml_file):
    """Locate the mdoc for an XML: ``<stem>.mdoc`` first (Warp 1 / PACE:
    ``X.mrc.xml`` -> ``X.mrc.mdoc``), then common variants."""
    stem = os.path.splitext(os.path.basename(xml_file))[0]
    root_stem = os.path.splitext(stem)[0]
    for cand in (stem + ".mdoc", stem + ".mrc.mdoc", stem + ".st.mdoc",
                 root_stem + ".mdoc", root_stem + ".mrc.mdoc"):
        path = os.path.join(mdoc_dir, cand)
        if os.path.exists(path):
            return path
    return None


def _parse_mdoc_time(value):
    value = " ".join(value.split())
    for fmt in ("%d-%b-%Y %H:%M:%S", "%d-%b-%y %H:%M:%S"):
        try:
            return datetime.strptime(value, fmt)
        except ValueError:
            pass
    return None


def read_mdoc_doses(path):
    """Accumulated (pre-exposure) dose per tilt from a SerialEM mdoc.

    Tilts are put in acquisition order (TimeStamp, else DateTime, else ZValue)
    and each tilt's dose is the sum of ``ExposureDose`` of every tilt acquired
    before it -- the same convention WarpTools ``ts_import`` writes to
    ``_wrpDose`` (first tilt = 0), but with the measured per-tilt exposure.

    Returns {movie_stem: dose}. Raises ValueError if the mdoc lacks
    SubFramePath or ExposureDose.
    """
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    entries, cur = [], None
    for line in lines:
        s = line.strip()
        if s.startswith("[ZValue"):
            cur = {"ZValue": int(s.split("=")[1].strip(" ]"))}
            entries.append(cur)
        elif s.startswith("["):
            cur = None
        elif cur is not None and " = " in s:
            k, v = s.split(" = ", 1)
            cur[k.strip()] = v.strip()
    if not entries:
        raise ValueError(f"{os.path.basename(path)}: no [ZValue] sections")
    for e in entries:
        if "SubFramePath" not in e:
            raise ValueError(f"{os.path.basename(path)}: ZValue {e['ZValue']} "
                             "has no SubFramePath (needed to match tilts)")
        if "ExposureDose" not in e:
            raise ValueError(f"{os.path.basename(path)}: ZValue {e['ZValue']} "
                             "has no ExposureDose")

    if all("TimeStamp" in e for e in entries):
        key = lambda e: (float(e["TimeStamp"]), e["ZValue"])
    elif all(_parse_mdoc_time(e.get("DateTime", "")) for e in entries):
        key = lambda e: (_parse_mdoc_time(e["DateTime"]), e["ZValue"])
    else:
        key = lambda e: e["ZValue"]

    doses, acc = {}, 0.0
    for e in sorted(entries, key=key):
        stem = _stem(e["SubFramePath"])
        if stem in doses:
            raise ValueError(f"{os.path.basename(path)}: movie {stem} listed twice")
        doses[stem] = acc
        acc += float(e["ExposureDose"])
    return doses


def mdoc_doses_for_xml(root, mdoc_path):
    """mdoc doses aligned to the XML tilt index (matched by movie name)."""
    by_stem = read_mdoc_doses(mdoc_path)
    stems = [_stem(p) for p in split_lines(root.find("MoviePath").text)]
    missing = [s for s in stems if s not in by_stem]
    if missing:
        raise ValueError(
            f"{len(missing)} XML movie(s) not found in "
            f"{os.path.basename(mdoc_path)}, e.g. {missing[0]}")
    return [by_stem[s] for s in stems]


def format_dose(x):
    """Compact float text, like Warp's (``0``, ``2.8483``, ``102.5381``)."""
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def dose_differences(old, new, tol=DOSE_TOL):
    """[(index, old, new)] for entries that differ by more than ``tol``.
    Entries whose new value is None (= leave unchanged) are ignored."""
    return [(i, a, b) for i, (a, b) in enumerate(zip(old, new))
            if b is not None and abs(a - b) > tol]


def set_xml_doses(root, doses):
    """Override <Dose> in place; returns the differences vs. the old values."""
    return set_xml_values(root, "Dose", doses, DOSE_TOL)


def set_xml_values(root, tag, values, tol):
    """Override the per-tilt list <tag> in place. ``values[i] is None`` keeps
    the existing entry verbatim. Returns [(index, old, new)] differences."""
    el = root.find(tag)
    lines = split_lines(el.text)
    old = [float(x) for x in lines]
    el.text = "\n".join(lines[i] if v is None else format_dose(v)
                         for i, v in enumerate(values))
    return dose_differences(old, values, tol)


def dose_warning(label, diffs, n, src, unit="view", quantity="doses",
                 units="e/A^2"):
    """One-line warning summarising value differences (or None)."""
    if not diffs:
        return None
    worst = max(diffs, key=lambda d: abs(d[1] - d[2]))
    return (f"WARNING: {label} {quantity} differ from {src} for {len(diffs)}/{n} "
            f"tilts (largest: {unit} {worst[0] + 1} {format_dose(worst[1])} -> "
            f"{format_dose(worst[2])} {units}); overriding with {src} values.")


# --------------------------------------------------------------------------- #
# Tilt angles from taSolution.log (--angles-from-log)
# --------------------------------------------------------------------------- #
ANGLE_TOL = 0.005  # deg
MIN_ANGLE_CORR = 0.8   # below this the log cannot belong to this XML
LARGE_ANGLE_CHANGE = 5.0  # deg; flag big etomo corrections for a check


def _best_sign(old, new):
    """+1 or -1: the sign that makes ``new`` agree best with ``old``."""
    plus = sum(abs(a - b) for a, b in zip(old, new))
    minus = sum(abs(a + b) for a, b in zip(old, new))
    return -1 if minus < plus else 1


def _corr(x, y):
    n = len(x)
    mx, my = sum(x) / n, sum(y) / n
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y))
    sxx = sum((a - mx) ** 2 for a in x)
    syy = sum((b - my) ** 2 for b in y)
    return sxy / (sxx * syy) ** 0.5 if sxx and syy else 1.0


def log_angles_for_xml(root, tilts_in_log):
    """Per-XML-tilt angles from taSolution.log: ``[angle or None]`` (None for
    views not in the log, which are left unchanged).

    The sign is matched to the XML's own <Angles> (Warp normally stores them
    with etomo's sign; AreAnglesInverted is applied by Warp at use time).
    Raises ValueError if the log does not track the XML angles at all
    (corr < 0.8), which means view numbers and XML tilts do not line up.
    """
    n = get_n_tilts(root)
    old = [float(a) for a in split_lines(root.find("Angles").text)]
    idx = [i for i in range(n) if (i + 1) in tilts_in_log]
    if not idx:
        raise ValueError("no taSolution.log views match XML tilts")
    if max(idx) >= n:
        raise ValueError(f"log has view {max(idx) + 1} but XML has {n} tilts")
    o = [old[i] for i in idx]
    t = [tilts_in_log[i + 1] for i in idx]
    sign = _best_sign(o, t)
    t = [sign * x for x in t]
    if len(idx) > 2 and _corr(o, t) < MIN_ANGLE_CORR:
        raise ValueError("taSolution.log tilts do not follow the XML angles "
                         "(view numbering mismatch?)")
    out = [None] * n
    for i, a in zip(idx, t):
        out[i] = a
    return out


# --------------------------------------------------------------------------- #
# Overrides: per-tilt values written to the XML and the tomostar.
# --------------------------------------------------------------------------- #
class Override:
    """Per-XML-tilt values (None = keep) for one XML list + tomostar column."""

    def __init__(self, xml_tag, tomostar_col, values, src, quantity, units,
                 tol, match_tomostar_sign=False):
        self.xml_tag = xml_tag
        self.tomostar_col = tomostar_col
        self.values = values
        self.src = src
        self.quantity = quantity
        self.units = units
        self.tol = tol
        self.match_tomostar_sign = match_tomostar_sign

    def warn(self, label, diffs, n, unit="view"):
        msg = dose_warning(label, diffs, n, self.src, unit=unit,
                           quantity=self.quantity, units=self.units)
        if msg and self.xml_tag == "Angles" and label == "XML":
            big = [d for d in diffs if abs(d[1] - d[2]) > LARGE_ANGLE_CHANGE]
            if big:
                msg += (f"\n    WARNING: {len(big)} tilt angles change by more "
                        f"than {LARGE_ANGLE_CHANGE:g} deg; check the etomo "
                        "alignment before reconstructing.")
        return msg


def dose_override(doses):
    return Override("Dose", "_wrpDose", doses, "mdoc", "doses", "e/A^2",
                    DOSE_TOL)


def angle_override(angles):
    return Override("Angles", "_wrpAngleTilt", angles, "taSolution.log",
                    "tilt angles", "deg", ANGLE_TOL, match_tomostar_sign=True)


# --------------------------------------------------------------------------- #
# Structure validation (pre-edit abort and post-edit assertion)
# --------------------------------------------------------------------------- #
def validate_structure(root, n):
    """Check every per-tilt structure is consistent at count ``n``.

    Returns a list of error strings; empty means the file is safe to edit.
    Aborting on any mismatch guarantees we never write a partially-edited file.
    """
    errors = []
    for el in root:
        if len(el) > 0 or "ID" in el.attrib or el.text is None:
            continue
        lines = split_lines(el.text)
        if len(lines) > 1 and len(lines) != n:
            errors.append(f"<{el.tag}> has {len(lines)} entries, expected {n}")

    # Indexed groups (TiltPS1D, TiltSimulatedScale, ...) must be exactly 0..N-1.
    groups = defaultdict(list)
    for el in root:
        if "ID" in el.attrib:
            groups[el.tag].append(el)
    for tag, els in groups.items():
        ids = sorted(int(e.get("ID")) for e in els)
        if ids != list(range(n)):
            errors.append(
                f"<{tag}> ID set is {ids[:3]}...({len(ids)}), expected 0..{n - 1}"
            )

    # Per-tilt grids must have W*H*N nodes and Z == 0..N-1.
    for grid in per_tilt_grids(root, n):
        w = int(grid.get("Width"))
        h = int(grid.get("Height"))
        nodes = grid.findall("Node")
        if len(nodes) != w * h * n:
            errors.append(
                f"<{grid.tag}> has {len(nodes)} nodes, expected W*H*Depth={w * h * n}"
            )
        zs = sorted(set(int(nd.get("Z")) for nd in nodes))
        if zs != list(range(n)):
            errors.append(f"<{grid.tag}> Z range is not 0..{n - 1}")
    return errors


def assert_after_delete(root, m):
    """Re-check every per-tilt list length and every grid Depth/Z range against
    the surviving tilt count M. Raises AssertionError on any corruption."""
    for el in per_tilt_text_elems(root, m):
        assert len(split_lines(el.text)) == m, f"<{el.tag}> length != {m} after edit"
    for tag, els in per_tilt_indexed(root, m).items():
        ids = sorted(int(e.get("ID")) for e in els)
        assert ids == list(range(m)), f"<{tag}> IDs not 0..{m - 1} after edit"
    for grid in per_tilt_grids(root, m):
        w = int(grid.get("Width"))
        h = int(grid.get("Height"))
        assert int(grid.get("Depth")) == m, f"<{grid.tag}> Depth != {m}"
        nodes = grid.findall("Node")
        assert len(nodes) == w * h * m, f"<{grid.tag}> node count != W*H*{m}"
        zs = sorted(set(int(nd.get("Z")) for nd in nodes))
        assert zs == list(range(m)), f"<{grid.tag}> Z not 0..{m - 1} after edit"


# --------------------------------------------------------------------------- #
# The delete edit (in memory)
# --------------------------------------------------------------------------- #
def delete_tilts_in_xml(root, n, deleted):
    """Physically remove ``deleted`` (a set of 0-based tilt indices) from every
    per-tilt structure, renumbering grid Z / indexed IDs to be contiguous.
    Returns M, the number of surviving tilts."""
    keep = [i for i in range(n) if i not in deleted]
    m = len(keep)
    zmap = {old: new for new, old in enumerate(keep)}

    # Gather targets up front (before we start mutating the tree).
    text_elems = per_tilt_text_elems(root, n)
    indexed = per_tilt_indexed(root, n)
    grids = per_tilt_grids(root, n)

    # 1. Per-tilt text lists: keep surviving entries, preserving formatting.
    for el in text_elems:
        lines = split_lines(el.text)
        el.text = "\n".join(lines[i] for i in keep)

    # 2. Indexed elements: drop deleted, renumber surviving IDs 0..M-1.
    for els in indexed.values():
        els_sorted = sorted(els, key=lambda e: int(e.get("ID")))
        survivors = []
        for e in els_sorted:
            if int(e.get("ID")) in deleted:
                root.remove(e)
            else:
                survivors.append(e)
        for new_id, e in enumerate(survivors):
            e.set("ID", str(new_id))

    # 3. Per-tilt grids: drop deleted Z-slices, renumber Z, fix Depth + tails.
    for grid in grids:
        nodes = grid.findall("Node")
        inner_tail = nodes[0].tail if len(nodes) >= 2 else None
        close_tail = nodes[-1].tail
        survivors = []
        for nd in nodes:
            if int(nd.get("Z")) in deleted:
                grid.remove(nd)
            else:
                survivors.append(nd)
        for nd in survivors:
            nd.set("Z", str(zmap[int(nd.get("Z"))]))
        for i, nd in enumerate(survivors):
            if i == len(survivors) - 1:
                nd.tail = close_tail
            else:
                nd.tail = inner_tail if inner_tail is not None else close_tail
        grid.set("Depth", str(m))

    return m


def movie_basenames(root, n):
    """basename() of each per-tilt MoviePath entry (tilt index -> basename)."""
    mp = root.find("MoviePath")
    lines = split_lines(mp.text)
    return [os.path.basename(p.strip()) for p in lines]


# --------------------------------------------------------------------------- #
# tomostar (STAR loop_ block) editing -- minimal, format-preserving.
# --------------------------------------------------------------------------- #
def parse_tomostar(path):
    """Return (lines, cols, movie_col, data_idx) for a .tomostar file.

    ``lines`` is the file split on '\\n' (verbatim). ``data_idx`` are the line
    indices of the loop_ data rows. Non-data lines are preserved untouched.
    """
    with open(path, "r", encoding="utf-8", newline="") as fh:
        return parse_tomostar_text(fh.read())


def parse_tomostar_text(raw):
    """parse_tomostar on already-read text (see there)."""
    lines = raw.split("\n")
    loop_i = next(i for i, l in enumerate(lines) if l.strip() == "loop_")
    cols = []
    last_decl = loop_i
    j = loop_i + 1
    while j < len(lines) and lines[j].strip().startswith("_"):
        cols.append(lines[j].strip().split()[0])
        last_decl = j
        j += 1
    data_idx = []
    k = last_decl + 1
    while k < len(lines):
        if lines[k].strip() == "":
            if data_idx:  # a blank line after data marks the end of the block
                break
            k += 1
            continue
        data_idx.append(k)
        k += 1
    movie_col = cols.index("_wrpMovieName")
    return lines, cols, movie_col, data_idx


def delete_tomostar_rows(path, deleted, xml_basenames, n):
    """Compute the new tomostar text with the deleted tilts' rows removed.

    Rows are matched to XML tilts by movie basename; falls back to row order
    (with a warning) only if names can't be matched one-to-one. Returns
    (new_text, warning_or_None, surviving_row_count) or raises ValueError if the
    row count does not match N.
    """
    lines, cols, movie_col, data_idx = parse_tomostar(path)
    if len(data_idx) != n:
        raise ValueError(
            f"{os.path.basename(path)}: {len(data_idx)} rows != {n} XML tilts"
        )

    row_bn = [os.path.basename(lines[i].split()[movie_col]) for i in data_idx]
    names_ok = set(row_bn) == set(xml_basenames) and len(set(row_bn)) == len(row_bn)

    warning = None
    if names_ok:
        deleted_movies = {xml_basenames[i] for i in deleted}
        del_positions = {p for p, bn in enumerate(row_bn) if bn in deleted_movies}
    else:
        warning = (
            "movie names could not be matched to tomostar rows; "
            "falling back to row order"
        )
        del_positions = set(deleted)

    drop_line_idx = {data_idx[p] for p in del_positions}
    new_lines = [l for i, l in enumerate(lines) if i not in drop_line_idx]
    return "\n".join(new_lines), warning, len(data_idx) - len(del_positions)


def _replace_field(line, col, value):
    """Replace the ``col``-th whitespace-separated token, keeping all spacing
    (and any trailing CR) intact."""
    spans = [m.span() for m in re.finditer(r"\S+", line)]
    a, b = spans[col]
    return line[:a] + value + line[b:]


def set_tomostar_column(text, col, xml_basenames, values, tol=DOSE_TOL,
                        match_sign=False):
    """Write ``values`` (aligned to ``xml_basenames``; None = keep) into column
    ``col`` of tomostar ``text``. Rows are matched by movie basename, falling
    back to row order. With ``match_sign`` the values' sign is matched to the
    column's existing values (tomostar and XML may use opposite tilt signs).
    Returns (new_text, diffs, warning_or_None)."""
    lines, cols, movie_col, data_idx = parse_tomostar_text(text)
    if col not in cols:
        return text, [], f"tomostar has no {col} column; not written"
    c = cols.index(col)
    if len(data_idx) != len(values):
        raise ValueError(f"tomostar has {len(data_idx)} rows, expected {len(values)}")
    by_name = dict(zip(xml_basenames, values))
    row_bn = [os.path.basename(lines[i].split()[movie_col]) for i in data_idx]
    warning = None
    if set(row_bn) == set(by_name) and len(set(row_bn)) == len(row_bn):
        row_vals = [by_name[bn] for bn in row_bn]
    else:
        warning = ("movie names could not be matched to tomostar rows; "
                   f"{col} written in row order")
        row_vals = list(values)
    old = [float(lines[i].split()[c]) for i in data_idx]
    if match_sign:
        pairs = [(o, v) for o, v in zip(old, row_vals) if v is not None]
        if pairs:
            sign = _best_sign([p[0] for p in pairs], [p[1] for p in pairs])
            row_vals = [None if v is None else sign * v for v in row_vals]
    for i, v in zip(data_idx, row_vals):
        if v is not None:
            lines[i] = _replace_field(lines[i], c, format_dose(v))
    return "\n".join(lines), dose_differences(old, row_vals, tol), warning


def set_tomostar_doses(text, xml_basenames, doses):
    """Write doses into ``_wrpDose`` (see set_tomostar_column)."""
    return set_tomostar_column(text, "_wrpDose", xml_basenames, doses)


